/** Style / template gallery shown before the first prompt. */

export type StyleCategory =
  | "ads"
  | "nature"
  | "characters"
  | "typography"
  | "minimal"
  | "cinema"
  | "motion"
  | "tech"
  | "lifestyle"
  | "abstract";

export type StylePreset = {
  id: string;
  title: string;
  tag: string;
  category: StyleCategory;
  categoryLabel: string;
  /** short visual description for the gallery card */
  blurb: string;
  /** appended to the user prompt */
  prompt: string;
  colors: [string, string, string];
  aspect: "16:9" | "9:16" | "1:1";
  duration: number;
  /** hint on what kind of content to add */
  contentHint: string;
};

const CATEGORY_LABEL: Record<StyleCategory, string> = {
  ads: "Реклама и продажи",
  nature: "Природа",
  characters: "Персонажи и мультфильмы",
  typography: "Типографика и текст",
  minimal: "Минимализм",
  cinema: "Кино и атмосфера",
  motion: "Динамика и переходы",
  tech: "Технологии и код",
  lifestyle: "Лайфстайл и соцсети",
  abstract: "Абстракция и арт",
};

const P = (
  id: string,
  title: string,
  tag: string,
  category: StyleCategory,
  blurb: string,
  prompt: string,
  colors: [string, string, string],
  contentHint: string,
  aspect: "16:9" | "9:16" | "1:1" = "16:9",
  duration = 15,
): StylePreset => ({
  id,
  title,
  tag,
  category,
  categoryLabel: CATEGORY_LABEL[category],
  blurb,
  prompt,
  colors,
  contentHint,
  aspect,
  duration,
});

